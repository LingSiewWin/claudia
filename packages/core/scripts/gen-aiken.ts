function signed(f: AuthorizationFields, signature?: string): { fields: AuthorizationFields; signature: string } {
  return { fields: f, signature: signature ?? signAuthorization(f, ENGINE_TEST_SECRET).signature_hex };
}

// Amount 0 cannot pass the TS encoder, so a stolen engine key is modelled by signing patched bytes.
function signedAmountZero(): { fields: AuthorizationFields; signature: string } {
  const message = encodeAuthorization({ ...base, amount: 1n });
  const amountOffset = 22 + 1 + 28 + 28 + 32 + 4 + 32 + 1 + 28 + 1 + usdmName.length / 2;
  message.fill(0, amountOffset, amountOffset + 8);
  const signature = bytesToHex(signBytes(blake2b256(message), ENGINE_TEST_SECRET));
  return { fields: { ...base, amount: 0n }, signature };
}

