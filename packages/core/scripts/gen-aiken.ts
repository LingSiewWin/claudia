// Emits two Aiken modules from the TypeScript core, so the TS encoder stays the single source of truth:
// - vectors.test.ak: the committed authorization vectors, checked byte for byte in Aiken
// - fixtures.ak: engine-signed authorizations used by the vault validator tests

const AIKEN_LIB = new URL('../../../contracts/cardano/lib/authority/', import.meta.url);
const VECTORS_JSON = new URL('../test/vectors/authorization.json', import.meta.url);
const HEADER = '//// Generated by packages/core/scripts/gen-aiken.ts. Do not edit.';

const hex = (h: string) => `#"${h.toLowerCase()}"`;

function recipientFields(recipient: string): [number, string, number, string] {
  const a = parseShelleyAddress(recipient);
  const pay: [number, string] = [a.payment.tag === 'key' ? 0 : 1, bytesToHex(a.payment.hash)];
  if (!a.stake) return [...pay, 0, ''];
  return [...pay, a.stake.tag === 'key' ? 1 : 2, bytesToHex(a.stake.hash)];
}

function authLiteral(f: AuthorizationFields, indent: string): string {
  const [payTag, payHash, stakeTag, stakeHash] = recipientFields(f.recipient);
  const rows: Array<[string, string]> = [
    ['chain_tag', String(f.chainTag)],
    ['vault_hash', hex(f.vaultHash)],
    ['mandate_ref', hex(f.mandateRef)],
    ['mandate_hash', hex(f.mandateHash)],
    ['mandate_version', String(f.mandateVersion)],
    ['action_hash', hex(f.actionHash)],
    ['action_type', String(f.actionType)],
    ['asset_policy', hex(f.assetPolicy)],
    ['asset_name', hex(f.assetName)],
    ['amount', f.amount.toString()],
    ['recipient_pay_tag', String(payTag)],
    ['recipient_pay_hash', hex(payHash)],
    ['recipient_stake_tag', String(stakeTag)],
    ['recipient_stake_hash', hex(stakeHash)],
    ['nonce', f.nonce.toString()],
    ['valid_until', f.validUntil.toString()],
    ['requires_principal', f.requiresPrincipal ? '1' : '0'],
    ['verification_ref', hex(f.verificationRef ?? '00'.repeat(32))],
  ];
  const body = rows.map(([k, v]) => `${indent}  ${k}: ${v},`).join('\n');
  return `Authorization {\n${body}\n${indent}}`;
}

function snake(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

export function vectorsModule(): string {
  const vectors: Array<{ name: string; record: AuthorizationRecord }> = JSON.parse(readFileSync(VECTORS_JSON, 'utf8'));
  const tests = vectors.map(({ name, record }, i) => {
    const id = `vector_${i + 1}_${snake(name)}`;
    return [
      `test ${id}() {`,
      `  let auth = ${authLiteral(fieldsFromRecord(record), '  ')}`,
      `  let digest = message.digest(auth)`,
      `  and {`,
      `    message.encode(auth) == ${hex(record.message_hex)},`,
      `    digest == ${hex(record.digest_hex)},`,
      `    verify_ed25519_signature(`,
      `      engine_vkey,`,
      `      digest,`,
      `      ${hex(record.signature_hex)},`,
      `    ),`,
      `    !verify_ed25519_signature(`,
      `      engine_vkey,`,
      `      message.digest(Authorization { ..auth, nonce: auth.nonce + 1 }),`,
      `      ${hex(record.signature_hex)},`,
      `    ),`,
      `  }`,
      `}`,
    ].join('\n');
  });
  const engineVkey = vectors[0]?.record.engine_public_key ?? '';
  return [
    HEADER,
    '',
    'use aiken/crypto.{verify_ed25519_signature}',
    'use authority/message',
    'use authority/types.{Authorization}',
    '',
    `const engine_vkey =\n  ${hex(engineVkey)}`,
    '',
    tests.join('\n\n'),
    '',
  ].join('\n');
}

