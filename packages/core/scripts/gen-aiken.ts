export function fixturesModule(): string {
  const consts = fixtureCases().map(([name, { fields, signature }]) =>
    [
      `pub const ${name}: Signed =`,
      `  Signed {`,
      `    auth: ${authLiteral(fields, '    ')},`,
      `    signature: ${hex(signature)},`,
      `  }`,
    ].join('\n'),
  );
  return [
    HEADER,
    '',
    'use authority/types.{Authorization}',
    '',
    'pub type Signed {',
    '  auth: Authorization,',
    '  signature: ByteArray,',
    '}',
    '',
    `pub const engine_vkey: ByteArray =\n  ${hex(bytesToHex(publicKeyFromSecret(ENGINE_TEST_SECRET)))}`,
    '',
    consts.join('\n\n'),
    '',
  ].join('\n');
}

